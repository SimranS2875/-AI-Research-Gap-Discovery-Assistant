"""LLM access. Everything else in the app talks to the `LLMClient` interface, so the model
provider can be swapped (or faked in tests) without touching the pipeline."""
import json
import os
import re
import threading
import time
from abc import ABC, abstractmethod
from typing import Iterable, List, Optional, Sequence, Type, TypeVar

import numpy as np
from pydantic import BaseModel

T = TypeVar("T", bound=BaseModel)

# Free-tier keys allow as few as 5 requests/minute; 13 s between calls stays under that.
DEFAULT_MIN_INTERVAL_S = 13.0


class LLMError(Exception):
    def __init__(self, message: str, code: Optional[int] = None):
        super().__init__(message)
        self.code = code


class AuthError(LLMError):
    """API key rejected or not permitted."""


class QuotaExceededError(LLMError):
    """Daily quota is used up; retrying will not help."""


class LLMClient(ABC):
    @abstractmethod
    def default_model(self) -> str:
        """Name of the model used when none is given."""

    @abstractmethod
    def generate_json(self, prompt: str, schema: Type[T], *, model: Optional[str] = None,
                      system: Optional[str] = None) -> T:
        """Return an instance of `schema` generated by the model."""

    @abstractmethod
    def generate_text(self, prompt: str, *, model: Optional[str] = None,
                      system: Optional[str] = None) -> str:
        """Return free-form text."""

    @abstractmethod
    def embed(self, texts: Sequence[str]) -> np.ndarray:
        """Return one L2-normalised embedding row per text."""


# --------------------------------------------------------------------- model selection
_EXCLUDED_WORDS = (
    "lite", "image", "tts", "live", "audio", "embedding", "gemma", "learnlm", "robotics",
    "computer-use", "omni", "vision", "imagen", "veo", "aqa", "exp", "thinking",
    "customtools", "native",
)


def _strip_prefix(name: str) -> str:
    return name[len("models/"):] if name.startswith("models/") else name


def _version(name: str) -> tuple:
    m = re.search(r"gemini-(?:embedding-)?(\d+(?:\.\d+)*)", name)
    return tuple(int(x) for x in m.group(1).split(".")) if m else (0,)


def choose_generation_model(names: Iterable[str]) -> Optional[str]:
    """Pick a sensible default text model: the newest stable Flash model.

    The Gemini lineup changes often, so we pick from what the API reports instead of
    hard-coding a name. Flash is the cheapest model with a free tier."""
    names = [_strip_prefix(n) for n in names]
    if "gemini-flash-latest" in names:
        return "gemini-flash-latest"
    cands = [
        n for n in names
        if n.startswith("gemini-") and "flash" in n and not any(w in n for w in _EXCLUDED_WORDS)
    ]
    if not cands:
        return None
    # stable (no "preview") beats preview; then highest version
    return max(cands, key=lambda n: ("preview" not in n, _version(n), n))


def choose_embedding_model(names: Iterable[str]) -> Optional[str]:
    names = [_strip_prefix(n) for n in names]
    cands = [n for n in names if "embedding" in n]
    if not cands:
        return None
    return max(cands, key=lambda n: (n.startswith("gemini-"), "preview" not in n, _version(n), n))


# --------------------------------------------------------------------- error handling
_RETRY_IN = re.compile(r"retry in ([0-9.]+)s", re.IGNORECASE)
_RETRY_DELAY = re.compile(r"retryDelay['\"]?\s*:\s*['\"]?([0-9.]+)s", re.IGNORECASE)
_TRANSIENT_NAMES = {
    "ConnectError", "ConnectTimeout", "ReadTimeout", "RemoteProtocolError", "TimeoutException",
    "ReadError", "WriteError", "PoolTimeout",
}


def _is_daily_quota(msg: str) -> bool:
    low = msg.lower()
    return "perday" in low or "per day" in low or "daily" in low


def _suggested_delay(msg: str) -> Optional[float]:
    for rx in (_RETRY_IN, _RETRY_DELAY):
        m = rx.search(msg)
        if m:
            return float(m.group(1))
    return None


def _parse_json_model(text: str, schema: Type[T]) -> T:
    """Parse model output into `schema`, tolerating markdown fences and stray prose."""
    s = text.strip()
    s = re.sub(r"^```(?:json)?\s*", "", s)
    s = re.sub(r"\s*```$", "", s)
    try:
        return schema.model_validate_json(s)
    except ValueError:
        start, end = s.find("{"), s.rfind("}")
        if start != -1 and end > start:
            return schema.model_validate_json(s[start:end + 1])
        raise


# --------------------------------------------------------------------- Gemini client
class GeminiClient(LLMClient):
    def __init__(self, api_key: str, model: str = "", embedding_model: str = "",
                 max_retries: int = 4, timeout_s: int = 180,
                 min_interval_s: Optional[float] = None):
        if not api_key:
            raise AuthError("No Gemini API key provided. Set GEMINI_API_KEY (see README).")
        from google import genai
        from google.genai import types

        self._types = types
        self.client = genai.Client(
            api_key=api_key, http_options=types.HttpOptions(timeout=timeout_s * 1000)
        )
        self._model = model.strip()
        self._embedding_model = embedding_model.strip()
        self.max_retries = max_retries
        self._listing: Optional[List[tuple]] = None
        # Client-side throttle so we stay under the free-tier requests-per-minute cap
        # (as low as 5 RPM on some models). Set GEMINI_MIN_INTERVAL_S=0 for a paid key.
        if min_interval_s is None:
            try:
                min_interval_s = float(os.getenv("GEMINI_MIN_INTERVAL_S", "") or DEFAULT_MIN_INTERVAL_S)
            except ValueError:
                min_interval_s = DEFAULT_MIN_INTERVAL_S
        self.min_interval_s = max(0.0, min_interval_s)
        self._last_call = 0.0
        self._throttle_lock = threading.Lock()

    def _throttle(self) -> None:
        """Block until at least `min_interval_s` has passed since the previous request."""
        if self.min_interval_s <= 0:
            return
        with self._throttle_lock:
            wait = self._last_call + self.min_interval_s - time.monotonic()
            if wait > 0:
                time.sleep(wait)
            self._last_call = time.monotonic()

    # ---- models
    def list_models(self) -> List[tuple]:
        """[(name, supported_actions), ...] as reported by the API."""
        if self._listing is None:
            def call():
                return [(_strip_prefix(m.name or ""), list(m.supported_actions or []))
                        for m in self.client.models.list()]
            self._listing = self._retry(call)
        return self._listing

    def default_model(self) -> str:
        if self._model:
            return self._model
        names = [n for n, acts in self.list_models() if not acts or "generateContent" in acts]
        chosen = choose_generation_model(names)
        if not chosen:
            raise LLMError("Could not auto-detect a Gemini model. Set GEMINI_MODEL in your .env file.")
        self._model = chosen
        return chosen

    def embedding_model(self) -> str:
        if self._embedding_model:
            return self._embedding_model
        names = [n for n, acts in self.list_models() if not acts or "embedContent" in acts]
        chosen = choose_embedding_model(names)
        if not chosen:
            raise LLMError("Could not auto-detect an embedding model. Set GEMINI_EMBEDDING_MODEL.")
        self._embedding_model = chosen
        return chosen

    # ---- retry wrapper
    def _retry(self, fn):
        delay = 4.0
        for attempt in range(self.max_retries + 1):
            try:
                self._throttle()
                return fn()
            except LLMError:
                raise
            except Exception as e:  # SDK / network errors
                code = getattr(e, "code", None)
                msg = str(e)
                if code in (401, 403) or (code == 400 and ("API key" in msg or "API_KEY" in msg)):
                    raise AuthError(
                        "Gemini rejected the request (API key invalid or not permitted). "
                        "Check GEMINI_API_KEY.", code) from e
                if code == 404:
                    raise LLMError(f"Model or resource not found: {msg[:300]}", code) from e
                if code == 429 or "RESOURCE_EXHAUSTED" in msg:
                    if _is_daily_quota(msg):
                        raise QuotaExceededError(
                            "Gemini daily quota for this model is used up. Try a different model "
                            "(e.g. a Flash-Lite model), wait until the quota resets, or use a paid "
                            "key. Results already computed are cached and will not be re-requested.",
                            code) from e
                    transient = True
                elif code in (500, 502, 503, 504) or "UNAVAILABLE" in msg or "DEADLINE" in msg:
                    transient = True
                else:
                    transient = type(e).__name__ in _TRANSIENT_NAMES
                if not transient:
                    raise LLMError(f"Gemini request failed: {msg[:400]}", code) from e
                if attempt == self.max_retries:
                    raise LLMError(
                        f"Gemini is busy or rate-limited; gave up after {attempt + 1} tries: "
                        f"{msg[:300]}", code) from e
                wait = _suggested_delay(msg)
                time.sleep(min((wait + 1) if wait else delay, 60))
                delay *= 2
        raise LLMError("unreachable")  # pragma: no cover

    # ---- generation
    def _generate(self, model: str, prompt: str, system: Optional[str],
                  schema: Optional[Type[BaseModel]] = None, json_mode: bool = False) -> str:
        cfg = self._types.GenerateContentConfig(
            system_instruction=system or None,
            response_mime_type="application/json" if json_mode else None,
            response_schema=schema,
        )

        def call():
            return self.client.models.generate_content(model=model, contents=prompt, config=cfg)

        resp = self._retry(call)
        text = resp.text
        if not text:
            raise LLMError(f"Empty response from {model} (the reply may have been blocked or cut off).")
        return text

    def generate_text(self, prompt: str, *, model: Optional[str] = None,
                      system: Optional[str] = None) -> str:
        return self._generate(model or self.default_model(), prompt, system)

    def generate_json(self, prompt: str, schema: Type[T], *, model: Optional[str] = None,
                      system: Optional[str] = None) -> T:
        model = model or self.default_model()
        try:
            text = self._generate(model, prompt, system, schema=schema, json_mode=True)
            return _parse_json_model(text, schema)
        except (AuthError, QuotaExceededError):
            raise
        except (LLMError, ValueError) as first:
            # Fallback: describe the schema in the prompt instead of using structured output.
            fallback_prompt = (
                prompt
                + "\n\nReturn ONLY one JSON object (no markdown fences, no commentary) that "
                  "validates against this JSON Schema:\n"
                + json.dumps(schema.model_json_schema())
            )
            try:
                text = self._generate(model, fallback_prompt, system, json_mode=True)
                return _parse_json_model(text, schema)
            except (AuthError, QuotaExceededError):
                raise
            except (LLMError, ValueError) as second:
                raise LLMError(
                    f"Model did not return valid JSON. First error: {str(first)[:200]}; "
                    f"second error: {str(second)[:200]}") from second

    # ---- embeddings
    def embed(self, texts: Sequence[str]) -> np.ndarray:
        texts = [t if t.strip() else "." for t in texts]
        model = self.embedding_model()
        vectors: List[List[float]] = []
        for i in range(0, len(texts), 100):  # API limit: 100 texts per request
            batch = texts[i:i + 100]

            def call(batch=batch, with_task=True):
                cfg = (self._types.EmbedContentConfig(task_type="SEMANTIC_SIMILARITY")
                       if with_task else None)
                # One Content per text: newer embedding models (e.g. gemini-embedding-2) would
                # otherwise merge a list of plain strings into a single vector.
                contents = [self._types.Content(parts=[self._types.Part(text=t)]) for t in batch]
                return self.client.models.embed_content(model=model, contents=contents, config=cfg)

            try:
                resp = self._retry(call)
            except LLMError as e:
                if e.code == 400 and not isinstance(e, AuthError):
                    resp = self._retry(lambda: call(with_task=False))  # model may not accept task_type
                else:
                    raise
            if len(resp.embeddings) != len(batch):
                raise LLMError(
                    f"Embedding model returned {len(resp.embeddings)} vectors for {len(batch)} texts.")
            vectors.extend(list(e.values) for e in resp.embeddings)
        arr = np.asarray(vectors, dtype=np.float32)
        norms = np.linalg.norm(arr, axis=1, keepdims=True)
        return arr / np.where(norms == 0, 1, norms)
